import assert from 'node:assert/strict';
import { Game, gameFromSnapshot } from './js/game.js';
import { emptyBuild, buildCost, TOTAL_CREDITS } from './js/profile.js';
const build = { ...emptyBuild(), stats: { power: 2, speed: 1, defense: 1, agility: 1 }, weapon: 'magic', abilities: ['fireball', 'dashstrike'], augments: ['quickhands'] };
assert.equal(buildCost(build), TOTAL_CREDITS);
const player = (id, kit = build) => ({ id, name: id, color: '#38b6ff', build: kit });
const g = new Game([player('host'), player('friend')], 11, 'expanse');
const f = g.fighters[0];
assert.deepEqual(f.baseBuild, build);
assert.equal(f.st.weapon, 'magic');
assert.deepEqual(f.st.abilities, build.abilities);
assert.equal(f.score.cr, 0);
const over = { ...build, stats: { ...build.stats, power: 3 } };
assert.deepEqual(g.addFighter(player('late')).baseBuild, build);
assert.deepEqual(g.addFighter(player('over', over)).baseBuild, emptyBuild());
f.score.cr = 50000;
assert.equal(g.updateBuild('host', over), null);
assert.deepEqual(f.baseBuild, build);
assert.ok(g.updateBuild('host', emptyBuild()));
assert.ok(g.updateBuild('host', build));
assert.equal(f.score.cr, 50000);
f.score.cr = 0;
g._downFighter(f);
assert.deepEqual(f.baseBuild, build);
assert.equal(f.score.cr, 0);
assert.ok(!g.events.some(e => e.e === 'rebuild'));
g._respawnCoop(f);
assert.equal(f.dead, false);
assert.deepEqual(f.st.abilities, build.abilities);
assert.equal(f.st.weapon, build.weapon);
const revived = gameFromSnapshot([player('host'), player('friend'), player('late'), player('over', emptyBuild())], g.snapshot(), 11);
assert.deepEqual(revived.fighters[0].baseBuild, build);
assert.ok(revived.updateBuild('host', build));
assert.deepEqual(g.rebindFighter('late', player('returning')).baseBuild, build);
assert.deepEqual(g.rebindFighter('returning', player('bad-return', over)).baseBuild, emptyBuild());
console.log('PASS expedition builds: entry, late join, rejoin, 1000 CR cap, score independence, death/revive and host handoff');
